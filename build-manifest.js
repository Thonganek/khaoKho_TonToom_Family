#!/usr/bin/env node
/*
 * Builds photos-manifest.js — the list of images the presentation loads automatically.
 * Reads file names only; original photos are never renamed, modified or copied.
 *
 *   node build-manifest.js                 (uses ./คัดแล้ว)
 *   node build-manifest.js "other_folder"  (any folder next to index.html)
 */
const fs = require('fs');
const path = require('path');

const folder = process.argv[2] || 'คัดแล้ว';
const dir = path.resolve(__dirname, folder);
const collator = new Intl.Collator(undefined, { numeric: true, sensitivity: 'base' });

const files = fs.readdirSync(dir, { withFileTypes: true })
  .filter(d => d.isFile() && /\.(jpe?g|png|webp)$/i.test(d.name))
  .map(d => d.name)
  .sort(collator.compare);

const out = `// Auto-generated by build-manifest.js — ${new Date().toISOString()}\n` +
  `window.PHOTO_MANIFEST = ${JSON.stringify({ folder: path.relative(__dirname, dir).split(path.sep).join('/'), files }, null, 2)};\n`;

fs.writeFileSync(path.join(__dirname, 'photos-manifest.js'), out, 'utf8');
console.log(`photos-manifest.js — ${files.length} images from ${dir}`);
